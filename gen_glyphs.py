#!/usr/bin/env python3
"""Draws the glyph sheet for matrix-rain.c into glyphs.h: 64 glyphs (half-width katakana and digits, mirrored as in
the film) in an 8x8 grid of 40x64 cells, one byte of brightness per pixel. Only needed to change font or glyphs.

    python3 gen_glyphs.py        needs Pillow and the Noto Sans Mono CJK JP font
"""
import subprocess
from PIL import Image, ImageDraw, ImageFont, ImageOps

COLS = ROWS = 8
CW, CH = 40, 64
chars = [chr(c) for c in range(0xFF66, 0xFF9C)] + list("0123456789")
assert len(chars) == COLS * ROWS

path = subprocess.check_output(["fc-match", "-f", "%{file}", "Noto Sans Mono CJK JP:bold"], text=True)
font = None
for index in range(16):  # the .ttc holds several families; find the Japanese monospace one
    try:
        candidate = ImageFont.truetype(path, 50, index=index)
    except OSError:
        break
    if candidate.getname()[0] == "Noto Sans Mono CJK JP":
        font = candidate
        break
if font is None:
    raise SystemExit("Noto Sans Mono CJK JP not found in " + path)

sheet = Image.new("L", (COLS * CW, ROWS * CH), 0)
for n, ch in enumerate(chars):
    cell = Image.new("L", (CW, CH), 0)
    left, top, right, bottom = font.getbbox(ch)
    ImageDraw.Draw(cell).text(((CW - (right - left)) / 2 - left, (CH - (bottom - top)) / 2 - top), ch, font=font, fill=255)
    sheet.paste(ImageOps.mirror(cell), ((n % COLS) * CW, (n // COLS) * CH))

data = sheet.tobytes()
with open("glyphs.h", "w") as out:
    out.write("/* Generated by gen_glyphs.py: do not edit. */\n")
    out.write("#define GLYPH_COLS %d\n#define GLYPH_ROWS %d\n#define GLYPHS_W %d\n#define GLYPHS_H %d\n" % (COLS, ROWS, *sheet.size))
    out.write("static const unsigned char glyphs[] = {\n")
    for i in range(0, len(data), 32):
        out.write(",".join(map(str, data[i:i + 32])) + ",\n")
    out.write("};\n")
